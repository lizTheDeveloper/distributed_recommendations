// Presentation (§9.1 layer 5): turn approved records into taste lists (format v1, docs/WEB_APP.md)
// that the web app bundles, plus a copy of each under apps/web/public/collections/ that anyone can
// subscribe to by URL. Link-only: each item is the canonical watch URL on the creator's own
// instance, and nothing is downloaded or rehosted (§8 distribution modes).
//   node curation/scripts/publish.mjs [--dry-run]
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, readRecords, transition, writeRecord } from "./lib.mjs";

const WEB = join(ROOT, "..", "apps", "web");
const LIMITS = { name: 80, description: 500, note: 280, items: 256 };
const AUTHOR = "Multiverse Video editors";
/** Rotating shelves are published once they have this many approved picks. */
const MIN_SHELF = 3;

const toUnix = (iso) => (iso ? Math.floor(Date.parse(iso) / 1000) : undefined);
const cap = (s, n) => (s.length > n ? s.slice(0, n - 1) + "…" : s);

/** Build the lists from records. Pure, so tests can call it. */
export function buildCollections(records, collections, shelfNames = {}) {
  const live = records.filter((r) => ["approved", "published"].includes(r.editorial.status) && r.editorial.reviewer);
  const byScore = (a, b) => b.editorial.score - a.editorial.score || a.id.localeCompare(b.id);
  const list = (name, description, recs, max = LIMITS.items) => {
    const items = recs
      .sort(byScore)
      .slice(0, max)
      .map((r) => {
        const item = { id: r.source.video_url };
        if (r.editorial.why_selected) item.note = cap(r.editorial.why_selected, LIMITS.note);
        const added = toUnix(r.editorial.reviewed_at);
        if (added) item.addedAt = added;
        return item;
      });
    const updatedAt = Math.max(0, ...items.map((i) => i.addedAt ?? 0)) || undefined;
    return { v: 1, name: cap(name, LIMITS.name), author: AUTHOR, description: cap(description, LIMITS.description), ...(updatedAt ? { updatedAt } : {}), items };
  };

  const out = [];
  for (const c of collections) {
    let recs;
    if (c.slug === "start-here") recs = live.filter((r) => r.editorial.shelves?.includes("start-here"));
    else if (c.slug === "classroom-ready") recs = live.filter((r) => r.editorial.shelves?.includes("classroom-ready") && r.verification.captions_verified);
    else recs = live.filter((r) => r.editorial.primary_collection === c.slug || r.editorial.secondary_collections?.includes(c.slug));
    if (recs.length) out.push({ slug: c.slug, list: list(c.name, c.promise, recs, c.maxItems) });
  }
  for (const [slug, name] of Object.entries(shelfNames)) {
    const recs = live.filter((r) => r.editorial.shelves?.includes(slug));
    if (recs.length >= MIN_SHELF) out.push({ slug, list: list(name.name, name.promise, recs) });
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dry = process.argv.includes("--dry-run");
  const { collections, rotatingShelves = {} } = JSON.parse(readFileSync(join(ROOT, "collections.json"), "utf8"));
  const all = readRecords();
  const built = buildCollections(all.map((x) => x.rec), collections, rotatingShelves);
  const used = new Set(built.flatMap((c) => c.list.items.map((i) => i.id)));
  for (const c of built) console.log(`${c.slug}: ${c.list.items.length} item(s)`);
  if (dry) process.exit(0);

  writeFileSync(join(WEB, "src", "editorial.json"), JSON.stringify({ $comment: "Generated by curation/scripts/publish.mjs from human-approved curation/records. Don't edit by hand.", collections: built }, null, 2) + "\n");
  const dir = join(WEB, "public", "collections");
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (f.endsWith(".json")) rmSync(join(dir, f));
  for (const c of built) writeFileSync(join(dir, `${c.slug}.json`), JSON.stringify(c.list, null, 2) + "\n");
  writeFileSync(join(dir, "index.json"), JSON.stringify({ v: 1, collections: built.map((c) => ({ slug: c.slug, name: c.list.name, url: `collections/${c.slug}.json`, items: c.list.items.length })) }, null, 2) + "\n");

  for (const { file, rec } of all) {
    if (rec.editorial.status === "approved" && used.has(rec.source.video_url)) {
      transition(rec, "published", "publish.mjs", `in ${built.filter((c) => c.list.items.some((i) => i.id === rec.source.video_url)).map((c) => c.slug).join(", ")}`);
      writeRecord(file, rec);
    }
  }
}
