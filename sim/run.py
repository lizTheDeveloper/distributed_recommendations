"""Command-line entry point.

    python3 -m sim.run --all                 # every experiment, default sizes
    python3 -m sim.run --exp 1 3             # selected experiments
    python3 -m sim.run --all --quick         # tiny world, for smoke testing (~1 min)

Outputs go to sim/out/ (or --out DIR): per-experiment CSVs and expN_summary.md,
plus ALL_SUMMARIES.md concatenating the summaries.
"""
from __future__ import annotations

import argparse
import os
import platform
import sys
import time

import numpy as np

from . import exp1_quality, exp2_explore, exp3_circles, exp4_psi, exp5_sybil
from .common import out_path
from .world import QUICK, WorldConfig


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Match Feed simulation harness")
    ap.add_argument("--exp", type=int, nargs="*", default=[], help="experiments to run (1-5)")
    ap.add_argument("--all", action="store_true", help="run all experiments")
    ap.add_argument("--quick", action="store_true", help="tiny world for smoke tests")
    ap.add_argument("--seed", type=int, default=0, help="base seed")
    ap.add_argument("--out", default=None, help="output directory (default sim/out)")
    ap.add_argument("--workers", type=int, default=None, help="processes (default min(4, cpus))")
    a = ap.parse_args(argv)
    exps = [1, 2, 3, 4, 5] if a.all else a.exp
    if not exps:
        ap.print_help()
        return 2
    base = QUICK if a.quick else WorldConfig()
    sd = a.seed
    t_all = time.time()
    md = [f"<!-- generated by python3 -m sim.run {' '.join(argv or sys.argv[1:])}; "
          f"python {platform.python_version()}, numpy {np.__version__} -->"]
    for e in exps:
        t0 = time.time()
        print(f"[exp{e}] running...", flush=True)
        if e == 1:
            seeds = (sd,) if a.quick else (sd, sd + 1, sd + 2)
            r = exp1_quality.run(seeds=seeds, cfg=base, out_dir=a.out)
        elif e == 2:
            cfg = base if a.quick else WorldConfig(n_viewers=1500, n_creators=1000)
            seeds = (sd,) if a.quick else (sd, sd + 1)
            kw = dict(shares=(0.0, 0.05), random_shares=(0.05,), sens_shares=(0.0,)) \
                if a.quick else {}
            r = exp2_explore.run(seeds=seeds, cfg=cfg, out_dir=a.out, workers=a.workers, **kw)
        elif e == 3:
            kw = dict(ks=(5, 12), n_circles=10, n_items=60) if a.quick else {}
            r = exp3_circles.run(seed=sd, cfg=base, out_dir=a.out, workers=a.workers, **kw)
        elif e == 4:
            r = exp4_psi.run(seed=sd, cfg=base, n_pairs=400 if a.quick else 3000, out_dir=a.out)
        elif e == 5:
            kw = dict(sybils=(10, 100), edges=(0, 10)) if a.quick else {}
            r = exp5_sybil.run(seed=sd, cfg=base, out_dir=a.out, workers=a.workers, **kw)
        else:
            print(f"unknown experiment {e}", file=sys.stderr)
            return 2
        print(f"[exp{e}] done in {time.time() - t0:.1f}s", flush=True)
        md.append(r["markdown"])
    with open(out_path("ALL_SUMMARIES.md", a.out), "w") as f:
        f.write("\n\n".join(md) + "\n")
    print(f"all done in {time.time() - t_all:.1f}s; outputs in "
          f"{a.out or os.path.dirname(out_path('x'))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
